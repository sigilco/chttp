// Bake a built asset tree (vite dist/) into src/assets.gen.ts: an
// EmbeddedAssets subclass whose constructor loads an array of
// EmbedRecord records. This is the JSON-baked variant of the assets
// recipe — see docs/static.md "Baking assets into the binary" for the
// tradeoffs vs an FFI-linked blob.
//
// Usage: node scripts/bake.mjs [distDir] [outFile]
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const distDir = process.argv[2] ?? "dist";
const outFile = process.argv[3] ?? "src/assets.gen.ts";

const MIME = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".mjs": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".json": "application/json",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".gif": "image/gif",
  ".webp": "image/webp",
  ".ico": "image/x-icon",
  ".woff": "font/woff",
  ".woff2": "font/woff2",
  ".txt": "text/plain; charset=utf-8",
  ".map": "application/json",
};

const sha1 = (b) => createHash("sha1").update(b).digest("hex");

// Content-hashed filename: same heuristic as @chttp/static's isHashedName —
// the last `-`/`.` separated stem token is 8-32 alphanumerics mixing
// letters and digits.
function isHashed(name) {
  const stem = name.replace(/\.[^.]*$/, "");
  const tok = stem.split(/[-.]/).pop() ?? "";
  return (
    tok.length >= 8 &&
    tok.length <= 32 &&
    /^[A-Za-z0-9]+$/.test(tok) &&
    /[A-Za-z]/.test(tok) &&
    /[0-9]/.test(tok)
  );
}

function* walk(dir) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) yield* walk(p);
    else if (e.isFile()) yield p;
  }
}

// Collect real files, then attach .br/.gz siblings as encodings of the
// file they compress.
const files = [...walk(distDir)].filter((p) => !p.endsWith(".br") && !p.endsWith(".gz"));

const records = [];
for (const file of files) {
  const rel = relative(distDir, file).split("\\").join("/");
  const body = readFileSync(file);
  const encs = [];
  for (const enc of ["br", "gz"]) {
    const sib = file + "." + enc;
    try {
      encs.push({
        enc,
        b64: readFileSync(sib).toString("base64"),
        etag: sha1(readFileSync(sib)),
      });
    } catch {
      /* no sibling */
    }
  }
  records.push({
    path: rel,
    type: MIME[rel.slice(rel.lastIndexOf("."))] ?? "application/octet-stream",
    b64: body.toString("base64"),
    etag: sha1(body),
    mtimeMs: Math.floor(statSync(file).mtimeMs),
    immutable: isHashed(rel.split("/").pop() ?? ""),
    encs,
  });
}

const out = `// Generated by scripts/bake.mjs — do not edit. Re-run \`pnpm bake\`
// after every vite build. The records array is program data in the
// scriptc subset: an array of records, never a path-keyed object.
import { EmbeddedAssets } from "@chttp/static";
import type { EmbedRecord } from "@chttp/static";

const RECORDS: EmbedRecord[] = ${JSON.stringify(records, null, 2)};

export class BakedAssets extends EmbeddedAssets {
  constructor() {
    super();
    this.load(RECORDS);
  }
}
`;

writeFileSync(outFile, out);
console.log(`baked ${records.length} assets -> ${outFile}`);
